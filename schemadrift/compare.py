"""Compare an expected schema (source of truth) against a live schema."""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from .model import COMPATIBLE, Column, Schema

SEVERITY_ORDER = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]

JUNK_PATTERNS = [
    r"_(bak|backup|old|tmp|temp|copy|test)\d*$",
    r"^(bak|backup|tmp|temp|test|copy)_",
    r"_\d{6,8}$",            # date-stamped copies, e.g. invoice_20240115
]


@dataclass
class Mismatch:
    table: str
    column: str
    expected: str
    actual: str
    severity: str
    reason: str


@dataclass
class DriftReport:
    expected_only_tables: list[str] = field(default_factory=list)
    actual_only_tables: list[str] = field(default_factory=list)
    junk_tables: list[str] = field(default_factory=list)
    missing_columns: list[tuple[str, Column]] = field(default_factory=list)   # in expected, not in DB
    extra_columns: list[tuple[str, Column]] = field(default_factory=list)     # in DB, not in expected
    mismatches: list[Mismatch] = field(default_factory=list)
    tables_compared: int = 0

    @property
    def is_clean(self) -> bool:
        return not (self.expected_only_tables or self.missing_columns or
                    any(m.severity in ("CRITICAL", "HIGH") for m in self.mismatches))

    def severity_counts(self) -> dict[str, int]:
        counts = {s: 0 for s in SEVERITY_ORDER}
        for m in self.mismatches:
            counts[m.severity] += 1
        return counts


def is_junk(table: str) -> bool:
    return any(re.search(p, table, re.I) for p in JUNK_PATTERNS)


def grade(exp: Column, act: Column) -> tuple[str, str] | None:
    """Return (severity, reason) for a column pair, or None when identical."""
    if exp.type != act.type:
        if frozenset({exp.type, act.type}) in COMPATIBLE:
            return "MEDIUM", f"type family differs but is compatible ({exp.type} vs {act.type})"
        return "CRITICAL", f"incompatible types ({exp.type} vs {act.type})"

    if exp.length and act.length and exp.length != act.length:
        if act.length < exp.length:
            return "HIGH", f"DB column is narrower ({act.length} < {exp.length}) - inserts can fail"
        return "LOW", f"DB column is wider ({act.length} > {exp.length})"

    if exp.precision is not None and act.precision is not None:
        e_int = exp.precision - (exp.scale or 0)
        a_int = act.precision - (act.scale or 0)
        if a_int < e_int or (act.scale or 0) < (exp.scale or 0):
            return "HIGH", (f"DB numeric({act.precision},{act.scale or 0}) holds less than "
                            f"numeric({exp.precision},{exp.scale or 0})")
        if (a_int, act.scale) != (e_int, exp.scale):
            return "LOW", "DB numeric is wider than expected"

    if exp.nullable != act.nullable:
        if not exp.nullable and act.nullable:
            return "MEDIUM", "expected NOT NULL but DB allows NULL"
        return "MEDIUM", "DB is NOT NULL but code expects nullable - inserts without a value will fail"

    if exp.raw_type.lower() != act.raw_type.lower() and exp.describe() == act.describe():
        return "INFO", f"same after normalisation ({exp.raw_type} vs {act.raw_type})"
    return None


def compare(expected: Schema, actual: Schema) -> DriftReport:
    r = DriftReport()
    r.expected_only_tables = sorted(set(expected) - set(actual))
    actual_only = sorted(set(actual) - set(expected))
    r.junk_tables = [t for t in actual_only if is_junk(t)]
    r.actual_only_tables = [t for t in actual_only if not is_junk(t)]

    for name in sorted(set(expected) & set(actual)):
        r.tables_compared += 1
        e_cols, a_cols = expected[name].columns, actual[name].columns
        r.missing_columns += [(name, e_cols[c]) for c in sorted(set(e_cols) - set(a_cols))]
        r.extra_columns += [(name, a_cols[c]) for c in sorted(set(a_cols) - set(e_cols))]
        for c in sorted(set(e_cols) & set(a_cols)):
            g = grade(e_cols[c], a_cols[c])
            if g:
                r.mismatches.append(Mismatch(name, c, e_cols[c].describe(), a_cols[c].describe(), *g))

    r.mismatches.sort(key=lambda m: (SEVERITY_ORDER.index(m.severity), m.table, m.column))
    return r


def fix_sql(report: DriftReport, dialect: str = "postgres") -> str:
    """Generate a *draft* remediation script for missing columns and narrower DB columns."""
    lines = [f"-- Draft remediation generated by schema-drift-checker ({dialect}). REVIEW BEFORE RUNNING."]
    for table, col in report.missing_columns:
        t = col.describe() if dialect == "postgres" else col.describe().replace("varchar", "varchar2").replace(
            "numeric", "number")
        if dialect == "postgres":
            lines.append(f"ALTER TABLE {table} ADD COLUMN {col.name} {t};")
        else:
            lines.append(f"ALTER TABLE {table} ADD ({col.name} {t});")
    for m in report.mismatches:
        if m.severity == "HIGH":
            if dialect == "postgres":
                lines.append(f"ALTER TABLE {m.table} ALTER COLUMN {m.column} TYPE {m.expected};")
            else:
                t = m.expected.replace("varchar", "varchar2").replace("numeric", "number")
                lines.append(f"ALTER TABLE {m.table} MODIFY ({m.column} {t});")
    return "\n".join(lines) + "\n"
